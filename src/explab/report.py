"""Generate RESULTS.md and reports/VERDICT.md from results/*.json.

Charter gate: RESULTS.md is generated, never hand-typed. Every number
below is read from a result file written by an analysis module.
"""

import json
import math
from pathlib import Path

RESULTS = Path("results")
REPORTS = Path("reports")


def load(name):
    return json.loads((RESULTS / name).read_text(encoding="utf-8"))


def f4(x):
    return "n/a" if x is None else f"{x:.4f}"


def hypothesis_verdicts(primary_locked, causal, sequential):
    verdict = primary_locked["verdict"]
    branch = primary_locked["verdict_branch"]
    lo95, hi95 = primary_locked["ci95_log_or"]
    lo90, hi90 = primary_locked["ci90_log_or"]
    if branch == "ci95_excludes_0":
        h1 = "Supported"
        h2 = "Supported" if (lo90 > math.log(0.95) and hi90 < math.log(1.05)) else "Refuted"
    elif branch == "ci90_inside_sesoi_band":
        h1, h2 = "Refuted", "Supported"
    elif branch == "floor_cap_large_effect":
        h1, h2 = "Supported", "Refuted"
    else:
        h1 = h2 = "Inconclusive"
    gaps = [causal["ipw"]["gap_bootstrap_ci95"]]
    if causal["matching"]["gap_bootstrap_ci95"]:
        gaps.append(causal["matching"]["gap_bootstrap_ci95"])
    excludes = [not (g[0] <= 0 <= g[1]) for g in gaps]
    h3 = "Supported" if any(excludes) else "Refuted"
    aa = sequential["aa"]
    naive_ok = aa["naive_any_look_percent"] > 10
    msprt_ci = aa["msprt_any_look_ci95_percent"]
    msprt_ok = msprt_ci[0] <= 5.0 <= msprt_ci[1] or aa["msprt_any_look_percent"] <= 5.0
    if naive_ok and msprt_ok:
        h4 = "Supported"
    elif naive_ok or msprt_ok:
        h4 = "Partially supported"
    else:
        h4 = "Refuted"
    return {"H1": h1, "H2": h2, "H3": h3, "H4": h4, "primary_verdict": verdict}


def build_results_md():
    fetch = load("fetch.json")
    power = load("power.json")
    seq = load("sequential.json")
    audit = load("label_audit.json")
    guard = load("guardrails.json")
    pdev = load("primary_dev.json")
    plock = load("primary_locked.json")
    causal = load("causal.json")
    stress = load("stress.json")
    hv = hypothesis_verdicts(plock, causal, seq)
    g1 = guard["g1_exclusion_counts_full_file"]
    bal = guard["g2_balance_check_dev"]

    lines = []
    lines.append("# Results")
    lines.append("")
    lines.append("Generated by `python -m explab.report` from the JSON files in `results/`. Do not hand-edit. Reproduce with `make reproduce`.")
    lines.append("")
    lines.append("## 1. Data integrity (fetch gate, U4)")
    lines.append("")
    lines.append(f"- File: {fetch['file']}")
    lines.append(f"- SHA-256: {fetch['sha256']} (match with OSF-published value: {fetch['sha256_match']})")
    lines.append(f"- Size: {fetch['size_bytes']} bytes (expected {fetch['expected_size_bytes']})")
    lines.append(f"- Packages (rows): {fetch['packages_rows']} (documented {fetch['documented_packages']}, match: {fetch['packages_match_documented']})")
    lines.append(f"- Tests: {fetch['tests']} (documented {fetch['documented_tests']}, match: {fetch['tests_match_documented']})")
    lines.append("")
    lines.append("## 2. Power module (pack C1 to C4, from code)")
    lines.append("")
    lines.append(f"- C1 baseline CTR (estimate from published totals): {power['c1_baseline_ctr_percent']} percent")
    lines.append(f"- C2 mean arm size (estimate from published totals): {power['c2_mean_arm_size']} impressions")
    lines.append("")
    lines.append("| Relative lift | n per arm (computed) | Pack value | Match |")
    lines.append("| --- | --- | --- | --- |")
    for rel, row in power["c3_n_per_arm_by_relative_lift_percent"].items():
        lines.append(f"| {rel}% | {row['n_per_arm']} | {row['pack_value']} | {row['matches_pack']} |")
    lines.append("")
    lines.append(f"- Minimum detectable effect at the mean arm size: {power['c3_min_detectable_effect_percent_at_mean_arm']} percent relative (pack: {power['c3_min_detectable_effect_pack']})")
    lines.append("")
    lines.append("| Between-test SD (tau) | Tests needed (computed) | Pack value | Match |")
    lines.append("| --- | --- | --- | --- |")
    for tau, row in power["c4_tests_needed_by_tau"].items():
        lines.append(f"| {tau} | {row['tests_needed']} | {row['pack_value']} | {row['matches_pack']} |")
    lines.append("")
    lines.append("## 3. Sequential module (pack C5 and mSPRT, U7)")
    lines.append("")
    lines.append(f"Simulation: {seq['runs']} runs, seed {seq['seed']}, looks at {seq['looks_per_arm']} impressions per arm, baseline CTR {seq['baseline_ctr']}, mSPRT mixing SD {seq['tau_mix']}.")
    lines.append("")
    lines.append("| Stream | Naive, final look only | Naive, any of 7 looks | mSPRT, any look |")
    lines.append("| --- | --- | --- | --- |")
    for key, label in (("aa", "A/A (null true)"), ("ab_5pct_lift", "A/B (5% relative lift)")):
        r = seq[key]
        lines.append(f"| {label} | {r['naive_final_look_type1_or_power_percent']}% | {r['naive_any_look_percent']}% | {r['msprt_any_look_percent']}% |")
    ref = seq["pack_c5_reference"]
    lines.append("")
    lines.append(f"Pack C5 reference (its own simulation): final look {ref['final_look_percent']}% (CI {ref['final_look_ci95_percent']}), any look {ref['any_look_percent']}% (CI {ref['any_look_ci95_percent']}). The A/A row above is this study's independent reproduction with the same design and seed.")
    lines.append("")
    lines.append("## 4. Label audit")
    lines.append("")
    lines.append(f"- Sampled: {audit['n_sampled']} development-split headlines (100 per label group). Errors found by human review: {audit['n_errors']} (error rate {audit['error_rate']}).")
    for group, row in audit["by_group"].items():
        lines.append(f"- Group {group}: {row['errors']} errors in {row['n']} (rate {row['error_rate']})")
    lines.append("")
    lines.append("## 5. Guardrails (development split; full-file counts for G1)")
    lines.append("")
    lines.append(f"- G1 rows total: {g1['rows_total']}; tests total: {g1['tests_total']}; tests dropped by the problem-window exclusion: {g1['tests_dropped_window']} (rows {g1['rows_dropped_window']}); rows dropped for zero impressions: {g1['rows_dropped_zero_impressions']}; rows kept: {g1['rows_kept']}.")
    lines.append(f"- G2 balance / G3 placebo (same statistic, two readings): pooled log ratio of impressions per package, question over non-question: {f4(bal['log_ratio_impressions_per_package'])} (95% CI {bal['ci95']}, {bal['n_tests']} tests, tau {f4(bal['tau'])}).")
    lines.append("")
    lines.append("## 6. Primary analysis, development split (practice run, not the verdict)")
    lines.append("")
    lines.append(primary_block(pdev))
    lines.append("")
    lines.append("## 7. Primary analysis, locked split (the confirmatory result)")
    lines.append("")
    lines.append(primary_block(plock))
    lines.append("")
    lines.append(f"**Verdict (frozen rule, branch {plock['verdict_branch']}): {plock['verdict']}**")
    lines.append("")
    lines.append("## 8. Causal arm (development split)")
    lines.append("")
    lines.append(f"- Randomized benchmark (primary estimator, dev): log OR {f4(causal['benchmark_log_or'])} (95% CI {causal['benchmark_ci95_log_or']}; bootstrap CI {causal['benchmark_bootstrap_ci95_log_or']})")
    lines.append(f"- Naive cross-test estimate (no adjustment): log OR {f4(causal['naive_log_or'])}")
    lines.append(f"- IPW estimate: log OR {f4(causal['ipw']['log_or'])}; gap to benchmark {f4(causal['ipw']['gap_to_benchmark'])} (bootstrap 95% CI {causal['ipw']['gap_bootstrap_ci95']}); packages trimmed: {causal['ipw']['n_trimmed']}")
    m = causal["matching"]
    lines.append(f"- Matching estimate: log OR {f4(m['log_or'])} from {m['n_pairs']} pairs; gap to benchmark {f4(m['gap_to_benchmark'])} (bootstrap 95% CI {m['gap_bootstrap_ci95']})")
    lines.append("")
    lines.append("| Covariate | SMD raw | SMD after IPW | SMD after matching |")
    lines.append("| --- | --- | --- | --- |")
    for name, row in causal["balance"].items():
        lines.append(f"| {name} | {f4(row['smd_raw'])} | {f4(row['smd_ipw'])} | {f4(row['smd_matched'])} |")
    lines.append("")
    lines.append(f"Balance target: all adjusted SMDs below {causal['balance_target_abs_smd_below']} in absolute value. Bootstrap: {causal['bootstrap_runs']} cluster resamples over tests, seed {causal['seed']}. Overlap plot: reports/propensity_overlap.png.")
    lines.append("")
    lines.append("## 9. Stress tests (development split)")
    lines.append("")
    nc = stress["negative_control_starts_with_the"]
    sens = stress["sensitivity_ipw"]
    lines.append(f"- Placebo (impressions per package): section 5, G3 reading.")
    lines.append(f"- Negative control (headline starts with 'The'): log OR {f4(nc['log_or'])} (95% CI {nc['ci95_log_or']}, {nc['n_tests']} tests). No hypothesis is registered for this feature; a value far from 0 would signal residual structure.")
    lines.append(f"- Sensitivity (IPW): risk ratio {f4(sens['risk_ratio'])}; E-value {f4(sens['e_value'])}; bias needed to explain the full gap to the benchmark: {f4(sens['bias_to_explain_full_gap_log_or'])} log odds units (odds ratio factor {f4(sens['bias_to_explain_full_gap_or_factor'])}).")
    lines.append("")
    lines.append("## 10. Hypothesis verdicts (charter gate 9 words)")
    lines.append("")
    lines.append(f"- H1 (question headlines change CTR): {hv['H1']}")
    lines.append(f"- H2 (effect inside the plus or minus 5 percent band): {hv['H2']}")
    lines.append(f"- H3 (observational estimate misses the randomized benchmark): {hv['H3']}")
    lines.append(f"- H4 (peeking inflates false positives; mSPRT holds its rate): {hv['H4']}")
    lines.append("")
    return "\n".join(lines)


def primary_block(p):
    return (
        f"- Eligible tests: {p['n_tests']}\n"
        f"- Pooled log odds ratio: {f4(p['log_or'])} (SE {f4(p['se'])}); odds ratio {f4(p['odds_ratio'])}\n"
        f"- 95% CI (log OR): {p['ci95_log_or']}; 90% CI (log OR): {p['ci90_log_or']}\n"
        f"- Between-test SD tau: {f4(p['tau'])}; I squared: {f4(p['i2_percent'])} percent\n"
        f"- Tests with a zero cell (0.5 correction applied): {p['tests_continuity_corrected']}; tests dropped by the negative-nonclicks guard: {p['tests_dropped_negative_nonclicks']}"
    )


def build_verdict_md():
    plock = load("primary_locked.json")
    pdev = load("primary_dev.json")
    causal = load("causal.json")
    seq = load("sequential.json")
    hv = hypothesis_verdicts(plock, causal, seq)
    lo, hi = plock["ci95_odds_ratio"]
    claim = (
        f"In the locked confirmatory split of the Upworthy Research Archive exploratory data "
        f"({plock['n_tests']} eligible randomized tests), question headlines were associated with a "
        f"pooled odds ratio of {f4(plock['odds_ratio'])} for clicks versus non-question headlines in the "
        f"same tests (95% CI {lo} to {hi}, random-effects meta-analysis of within-test log odds ratios). "
        f"Under the verdict rule frozen before the data was touched, the verdict is {plock['verdict']}."
    )
    lines = []
    lines.append("# Verdict")
    lines.append("")
    lines.append("Generated by `python -m explab.report` from `results/primary_locked.json` and companion result files. Do not hand-edit.")
    lines.append("")
    lines.append(f"## Primary verdict: {plock['verdict']}")
    lines.append("")
    lines.append(f"Rule branch: {plock['verdict_branch']}. Eligible locked tests: {plock['n_tests']} (pre-registered floor: 190).")
    lines.append("")
    lines.append(claim)
    lines.append("")
    lines.append("## Supporting numbers")
    lines.append("")
    lines.append(f"- Development split (practice run of the same estimator): pooled log OR {f4(pdev['log_or'])} (95% CI {pdev['ci95_log_or']}, {pdev['n_tests']} tests), verdict word on dev alone would have been {pdev['verdict']}.")
    lines.append(f"- Causal arm (dev): IPW gap to the randomized benchmark {f4(causal['ipw']['gap_to_benchmark'])} log odds (bootstrap 95% CI {causal['ipw']['gap_bootstrap_ci95']}); matching gap {f4(causal['matching']['gap_to_benchmark'])} (bootstrap 95% CI {causal['matching']['gap_bootstrap_ci95']}).")
    lines.append(f"- Sequential module (A/A): naive peeking at 7 looks rejects {seq['aa']['naive_any_look_percent']}% of null streams; mSPRT rejects {seq['aa']['msprt_any_look_percent']}%.")
    lines.append("")
    lines.append("## Hypothesis verdicts")
    lines.append("")
    for h in ("H1", "H2", "H3", "H4"):
        lines.append(f"- {h}: {hv[h]}")
    lines.append("")
    lines.append("## Scope")
    lines.append("")
    lines.append("Upworthy, 2013 to 2015, outside the excluded randomization-problem window, exploratory split only. This is a reanalysis of archived experiments, not production A/B testing experience. Prior published work on this exact contrast exists (Fang and Wheeler 2026, on the confirmatory set); see docs/related_work.md.")
    lines.append("")
    return "\n".join(lines)


def run():
    RESULTS.mkdir(exist_ok=True)
    REPORTS.mkdir(exist_ok=True)
    Path("RESULTS.md").write_text(build_results_md(), encoding="utf-8")
    (REPORTS / "VERDICT.md").write_text(build_verdict_md(), encoding="utf-8")
    print("RESULTS.md and reports/VERDICT.md written")


if __name__ == "__main__":
    run()
